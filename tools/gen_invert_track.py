#!/usr/bin/env python3
"""Generates tweaks/model-cycles_OS1.13/49-invert-track.json: invert what the T1-T6 pads do with TRACK.

    Stock OS 1.13                          With this tweak
    plain pad press : selects + plays      selects silently
    TRACK + pad     : selects silently     selects + plays

(Personal tweak, so the text is in English; the upstream repo writes its generators in French.)

What the stock code does. PadsView's pad consumer (0x4001d180) handles a pad press like this:
  1. it selects the pad's track with 0x40023c90 (a no-op if that track is already selected);
  2. then it plays the note only if TRACK is NOT held:

        4001d36a: jsr  0x40023c90     ; select the track
        4001d370: addq.l #4,sp
        4001d372: tst.b d7            ; d7 = "TRACK held" = 0x4007faf4(2) (key code 2)
        4001d374: beq  0x4001d34e     ; TRACK not held -> go and play the note
        4001d376: tst.b d3            ; TRACK held: only the RETRIG + flag special case can still play
        4001d378: bne  0x4001d360
        4001d37a: bra  0x4001d3c8     ; end, silent

The tweak turns that one beq (0x67) into bne (0x66): the note is played only if TRACK is held. The branch
offset (0xd8) is unchanged. One byte, no free space used, nothing else touched.

Left alone on purpose: when the preset browser is open the code takes another path (a plain press still plays,
which is how a sound is previewed). There TRACK + pad now selects AND plays instead of only selecting.
Releasing a pad is safe: the release code only ends a note that was started (0x4001d3aa..), and a silent press
never starts one.

Needs only the Python standard library:

    python3 tools/gen_invert_track.py --cycles model-cycles_OS1.13.syx [--check]
"""
import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import build                                       # noqa: E402
from mtlib import aplib, container                 # noqa: E402
from mtlib.syx import unwrap                       # noqa: E402

OUT = HERE.parent / "tweaks" / "model-cycles_OS1.13" / "49-invert-track.json"
BASE = build.BASE                                  # VA of the first byte of section 3 (0x40000400)

BRANCH_VA = 0x4001d374                             # the beq: opcode byte 0x67 (beq), displacement byte 0xd8
OLD, NEW = bytes.fromhex("67"), bytes.fromhex("66")    # beq -> bne
# What must surround the branch in the official OS, so a different file can never be patched by mistake:
#   jsr 0x40023c90 ; addq.l #4,sp ; tst.b d7 ; [beq -0x28] ; tst.b d3 ; bne -0x1a ; bra +0x4c
CONTEXT_VA = 0x4001d36a
CONTEXT = bytes.fromhex("4eb940023c90" "588f" "4a07" "67d8" "4a03" "66e6" "604c")


def main_os_from_syx(path):
    """Section 3 (MAIN OS) of an official .syx, depacked. Same steps as build.py, no numpy needed."""
    stream, _ = unwrap(pathlib.Path(path).read_bytes())
    c = container.parse(stream)
    s3 = next(s for s in c["sections"] if s["id"] == 3)
    return aplib.depack(c["blob"][s3["off"]:s3["off"] + s3["size"]])[0]


def build_tweak(stock):
    got = stock[CONTEXT_VA - BASE:CONTEXT_VA - BASE + len(CONTEXT)]
    if got != CONTEXT:
        raise SystemExit(f"!! unexpected bytes around {BRANCH_VA:#x}: {got.hex()} (wanted {CONTEXT.hex()})")
    at = BRANCH_VA - BASE
    if stock[at:at + 1] != OLD or CONTEXT[BRANCH_VA - CONTEXT_VA] != OLD[0]:
        raise SystemExit(f"!! {BRANCH_VA:#x} is not a beq (0x67)")
    return {
        "id": "invert-track",
        "order": 49,
        "name": "Pads select silently, TRACK + pad plays",
        "description": [
            "T1-T6 pads: a plain press only selects the track (no sound). TRACK + pad selects the track and "
            "plays the sound. Stock OS: the reverse.",
            "Preset browser open: a plain press still plays (sound preview, stock). TRACK + pad there now "
            "selects and plays.",
            "One byte: beq -> bne at 0x4001d374 in PadsView's pad consumer (0x4001d180). No free space used. "
            "Generated by tools/gen_invert_track.py. Personal tweak, not part of the upstream project.",
        ],
        "device": "Model:Cycles",
        "os": "1.13",
        "section": 3,
        "writes": [{"off": at, "old": OLD.hex(), "new": NEW.hex()}],
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cycles", required=True, help="your official model-cycles_OS1.13.syx")
    ap.add_argument("--check", action="store_true", help="only check that the existing JSON is up to date")
    args = ap.parse_args()
    stock = main_os_from_syx(args.cycles)
    device = json.loads((OUT.parent / "device.json").read_text(encoding="utf-8"))
    if build.sha(stock) != device["section_sha256"]:
        raise SystemExit("!! this is not the official Model:Cycles OS 1.13 main program")
    tweak = build_tweak(stock)
    patched, dirty = build.apply_writes(stock, [tweak])        # the 'old' byte must match, or this stops here
    if sum(dirty) != 1 or sum(a != b for a, b in zip(stock, patched)) != 1:
        raise SystemExit("!! the patch must change exactly one byte")
    text = json.dumps(tweak, indent=1, ensure_ascii=False) + "\n"
    if args.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print(f"  {OUT.name} {'is up to date' if ok else 'DOES NOT MATCH'}")
        raise SystemExit(0 if ok else 1)
    OUT.write_text(text, encoding="utf-8")
    print(f"  wrote {OUT.relative_to(HERE.parent)}: 1 byte at offset {tweak['writes'][0]['off']} "
          f"({BRANCH_VA:#x}) {OLD.hex()} -> {NEW.hex()}")
    print("  next: python3 tools/build.py -i <your .syx> -t invert-track -o <output .syx>")


if __name__ == "__main__":
    main()
